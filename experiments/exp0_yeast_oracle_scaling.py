#!/usr/bin/env python
"""Yeast Exp 0 scaling on ensemble oracle pseudolabels.

Mirrors ``experiments/exp0_yeast_scaling.py`` but trains and evaluates on
the cached 5-DRNN + 5-DCNN ensemble pseudolabels generated by
``scripts/generate_yeast_ensemble_oracle.py``.

Train/val/test all use ensemble pseudolabels for their corresponding
sequence splits — so the comparison to the real-label arm is fair: both
arms use the same train sequences and the same val/test sequences,
they just differ in *what label* the model is supervised against.
"""

from __future__ import annotations

import json
import os
import time
from datetime import datetime
from pathlib import Path

import hydra
import numpy as np
import torch
import wandb
from dotenv import load_dotenv
from omegaconf import DictConfig, OmegaConf
from torch.utils.data import DataLoader, Dataset

from data.yeast import YeastDataset
from models.dream_rnn import create_dream_rnn
from models.loss_utils import YeastKLLoss
from models.training import train_model_optimized
from models.training_base import create_optimizer_and_scheduler

CONFIG: dict[str, object] = {}
REPO = Path(__file__).resolve().parents[1]


def set_seed(seed: int | None) -> int:
    if seed is None:
        seed = int.from_bytes(os.urandom(4), byteorder="big") % (2**31)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
    return seed


class _PseudoLabelYeastDataset(Dataset):
    """Wraps a base YeastDataset, swapping its labels for a numpy array."""

    def __init__(self, base: YeastDataset, labels: np.ndarray) -> None:
        if len(labels) != len(base):
            raise ValueError(f"label length {len(labels)} != dataset length {len(base)}")
        self.base = base
        self.labels = labels.astype(np.float32)

    def __len__(self) -> int:
        return len(self.base)

    def __getitem__(self, idx: int):
        x, _ = self.base[idx]
        y = torch.tensor(float(self.labels[idx]), dtype=torch.float32)
        return x, y

    def get_sequence_length(self) -> int:
        return self.base.get_sequence_length()


def _load_pseudolabels(npz_path: Path) -> np.ndarray:
    """Load mean ensemble pseudolabels from a generator npz file."""
    arr = np.load(npz_path, allow_pickle=True)
    return arr["labels"].astype(np.float32)


def run_fraction(
    fraction: float,
    train_dataset: _PseudoLabelYeastDataset,
    val_loader: DataLoader,
    device: torch.device,
    output_root: Path,
    seq_len: int,
    test_dataset: _PseudoLabelYeastDataset | None = None,
) -> dict:
    n_total = len(train_dataset)
    n_samples = max(1, int(n_total * fraction))
    indices = np.random.choice(n_total, size=n_samples, replace=False)
    from torch.utils.data import Subset

    train_subset = Subset(train_dataset, indices.tolist())
    train_loader = DataLoader(
        train_subset,
        batch_size=int(CONFIG["batch_size"]),
        shuffle=True,
        num_workers=int(CONFIG["num_workers"]),
        pin_memory=bool(CONFIG["pin_memory"]),
    )

    model = create_dream_rnn(
        input_channels=6,
        sequence_length=seq_len,
        task_mode="yeast",
        hidden_dim=int(CONFIG["hidden_dim"]),
        cnn_filters=int(CONFIG["cnn_filters"]),
        dropout_cnn=float(CONFIG["dropout_cnn"]),
        dropout_lstm=float(CONFIG["dropout_lstm"]),
    ).to(device)

    criterion = YeastKLLoss(reduction="batchmean")
    optimizer, scheduler = create_optimizer_and_scheduler(
        model=model,
        train_loader=train_loader,
        num_epochs=int(CONFIG["epochs"]),
        lr=float(CONFIG["lr"]),
        lr_lstm=float(CONFIG["lr_lstm"]),
        weight_decay=float(CONFIG["weight_decay"]),
        pct_start=float(CONFIG["pct_start"]),
    )

    checkpoint_dir = output_root / f"fraction_{fraction:.4f}"
    checkpoint_dir.mkdir(parents=True, exist_ok=True)

    start = time.time()
    history = train_model_optimized(
        model=model,
        train_loader=train_loader,
        val_loader=val_loader,
        optimizer=optimizer,
        criterion=criterion,
        num_epochs=int(CONFIG["epochs"]),
        device=device,
        scheduler=scheduler,
        checkpoint_dir=checkpoint_dir,
        use_reverse_complement=bool(CONFIG["use_reverse_complement"]),
        early_stopping_patience=CONFIG["early_stopping_patience"],
        metric_for_best=str(CONFIG["metric_for_best"]),
        use_amp=bool(CONFIG["use_amp"]),
        use_compile=bool(CONFIG["use_compile"]),
    )
    elapsed = time.time() - start

    best_val_pearson = max(history["val_pearson_r"]) if history["val_pearson_r"] else 0.0
    best_val_spearman = max(history["val_spearman_r"]) if history["val_spearman_r"] else 0.0
    best_val_loss = min(history["val_loss"]) if history["val_loss"] else float("inf")

    test_metrics: dict[str, float] = {}
    if test_dataset is not None:
        best_ckpt = checkpoint_dir / "best_model.pt"
        if best_ckpt.exists():
            model.load_checkpoint(str(best_ckpt))
        model.eval()
        test_loader = DataLoader(
            test_dataset,
            batch_size=int(CONFIG["batch_size"]),
            shuffle=False,
            num_workers=int(CONFIG["num_workers"]),
            pin_memory=bool(CONFIG["pin_memory"]),
        )
        preds: list[np.ndarray] = []
        with torch.no_grad():
            for xb, _ in test_loader:
                xb = xb.to(device, non_blocking=True)
                yhat = model.predict(
                    xb, use_reverse_complement=bool(CONFIG["use_reverse_complement"])
                )
                preds.append(yhat.detach().cpu().numpy().reshape(-1))
        test_pred = np.concatenate(preds, axis=0)
        test_lab = test_dataset.labels
        from scipy.stats import pearsonr, spearmanr

        test_metrics = {
            "in_dist": {
                "pearson_r": float(pearsonr(test_pred, test_lab)[0]),
                "spearman_r": float(spearmanr(test_pred, test_lab)[0]),
                "mse": float(np.mean((test_pred - test_lab) ** 2)),
                "n": int(len(test_lab)),
            }
        }

    result = {
        "fraction": fraction,
        "n_samples": n_samples,
        "n_total": n_total,
        "training_time_seconds": elapsed,
        "best_val_pearson_r": best_val_pearson,
        "best_val_spearman_r": best_val_spearman,
        "best_val_loss": best_val_loss,
        "num_epochs_run": len(history["val_loss"]),
        "test_metrics": test_metrics,
    }
    with (checkpoint_dir / "result.json").open("w", encoding="utf-8") as h:
        json.dump(result, h, indent=2)
    return result


@hydra.main(
    version_base=None,
    config_path="../configs/experiment",
    config_name="exp0_yeast_scaling",
)
def main(cfg: DictConfig) -> None:
    load_dotenv()
    global CONFIG
    CONFIG = OmegaConf.to_container(cfg, resolve=True)

    used_seed = set_seed(int(cfg.seed) if cfg.seed is not None else None)
    CONFIG["seed"] = cfg.seed

    if cfg.fraction is not None:
        fractions = [float(cfg.fraction)]
    elif cfg.fractions is not None:
        fractions = sorted([float(x) for x in cfg.fractions])
    else:
        fractions = [0.001, 0.002, 0.005, 0.01, 0.02, 0.05, 0.1, 0.2, 0.5, 1.0]

    device = torch.device(f"cuda:{int(cfg.gpu)}" if torch.cuda.is_available() else "cpu")

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_root = Path(str(cfg.output_dir)) / f"seed_{used_seed}"
    output_root.mkdir(parents=True, exist_ok=True)
    with (output_root / "config.json").open("w", encoding="utf-8") as h:
        json.dump({**CONFIG, "fractions": fractions, "device": str(device)}, h, indent=2)

    pseudolabel_dir = REPO / "outputs" / "yeast_ensemble_oracle"

    # Load datasets and override labels with ensemble pseudolabels
    train_base = YeastDataset(
        data_path=str(cfg.data_path), split="train", context_mode=str(cfg.context_mode)
    )
    train_pseudo = _load_pseudolabels(pseudolabel_dir / "train_pseudolabels.npz")
    train_dataset = _PseudoLabelYeastDataset(train_base, train_pseudo)
    seq_len = train_base.get_sequence_length()
    print(f"Train: {len(train_base):,} sequences (oracle pseudolabels)")

    val_base = YeastDataset(
        data_path=str(cfg.data_path), split="val", context_mode=str(cfg.context_mode)
    )
    val_pseudo = _load_pseudolabels(pseudolabel_dir / "val_pseudolabels.npz")
    val_dataset = _PseudoLabelYeastDataset(val_base, val_pseudo)
    val_loader = DataLoader(
        val_dataset,
        batch_size=int(cfg.batch_size),
        shuffle=False,
        num_workers=int(cfg.num_workers),
        pin_memory=bool(cfg.pin_memory),
    )
    print(f"Val:   {len(val_base):,} sequences (oracle pseudolabels)")

    test_base = YeastDataset(
        data_path=str(cfg.data_path), split="test", context_mode=str(cfg.context_mode)
    )
    test_pseudo = _load_pseudolabels(pseudolabel_dir / "test_pseudolabels.npz")
    test_dataset = _PseudoLabelYeastDataset(test_base, test_pseudo)
    print(f"Test:  {len(test_base):,} sequences (oracle pseudolabels)")

    wandb.init(
        project="albench-s2f",
        name=f"exp0_yeast_oracle_seed{used_seed}_{timestamp}",
        config={**CONFIG, "fractions": fractions},
        tags=["exp0", "yeast", "scaling", "oracle"],
        mode=str(cfg.wandb_mode),
    )

    for f in fractions:
        print(f"\n--- fraction={f} ---")
        run_fraction(f, train_dataset, val_loader, device, output_root, seq_len, test_dataset)


if __name__ == "__main__":
    main()
